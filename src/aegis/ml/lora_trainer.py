"""Production HuggingFace PEFT/LoRA & TRL DPO Fine-Tuning Runner for Open-Weights Guard Models."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Dict


def validate_or_run_lora_finetune(
    dpo_jsonl_path: str | Path,
    base_model_id: str = "meta-llama/Llama-3.2-3B-Instruct",
    output_dir: str | Path = "./aegis_state/lora_guard_adapter",
    dry_run: bool = True,
    lora_r: int = 16,
    lora_alpha: int = 32,
    learning_rate: float = 5e-5,
    num_epochs: int = 3,
) -> Dict[str, Any]:
    """
    Validates DPO preference-pair JSONL generated by `aegis finetune` and either:
      - (`dry_run=True`): Verifies schema, token/character lengths, and LoRA hyperparameter manifest
      - (`dry_run=False`): Launches HuggingFace `peft` LoRA + `trl.DPOTrainer` on CUDA / Apple MPS!
    """
    path = Path(dpo_jsonl_path)
    if not path.exists():
        raise FileNotFoundError(f"DPO dataset file not found: {path}")

    rows = [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]
    if not rows:
        raise ValueError("DPO JSONL dataset is empty.")

    for idx, r in enumerate(rows, start=1):
        for required_key in ("prompt", "chosen", "rejected"):
            if required_key not in r or not str(r[required_key]).strip():
                raise ValueError(f"Row {idx} missing required DPO key `{required_key}`.")

    lora_spec = {
        "base_model_id": base_model_id,
        "dataset_rows": len(rows),
        "peft_type": "LORA",
        "r": lora_r,
        "lora_alpha": lora_alpha,
        "target_modules": ["q_proj", "k_proj", "v_proj", "o_proj", "gate_proj", "up_proj", "down_proj"],
        "learning_rate": learning_rate,
        "num_train_epochs": num_epochs,
        "loss_type": "sigmoid_dpo",
        "output_dir": str(output_dir),
    }

    if dry_run:
        return {"status": "VALIDATED_READY", "dry_run": True, "lora_config": lora_spec}

    # Full GPU/MPS execution path (requires `pip install -e ".[lora]"`)
    import torch  # type: ignore
    from datasets import load_dataset  # type: ignore
    from peft import LoraConfig  # type: ignore
    from transformers import AutoModelForCausalLM, AutoTokenizer  # type: ignore
    from trl import DPOConfig, DPOTrainer  # type: ignore

    device_dtype = torch.bfloat16 if torch.cuda.is_available() else torch.float32
    tokenizer = AutoTokenizer.from_pretrained(base_model_id)
    if tokenizer.pad_token is None:
        tokenizer.pad_token = tokenizer.eos_token

    model = AutoModelForCausalLM.from_pretrained(base_model_id, torch_dtype=device_dtype)
    peft_cfg = LoraConfig(
        r=lora_r,
        lora_alpha=lora_alpha,
        lora_dropout=0.05,
        bias="none",
        task_type="CAUSAL_LM",
        target_modules=lora_spec["target_modules"],
    )
    ds = load_dataset("json", data_files=str(path), split="train")
    training_args = DPOConfig(
        output_dir=str(output_dir),
        learning_rate=learning_rate,
        num_train_epochs=num_epochs,
        per_device_train_batch_size=2,
        gradient_accumulation_steps=4,
        logging_steps=5,
        save_strategy="epoch",
    )
    trainer = DPOTrainer(
        model=model,
        args=training_args,
        train_dataset=ds,
        processing_class=tokenizer,
        peft_config=peft_cfg,
    )
    trainer.train()
    trainer.save_model(str(output_dir))
    return {"status": "TRAINED", "dry_run": False, "lora_config": lora_spec}
